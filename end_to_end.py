#Import the essential Azure libraries
from dotenv import load_dotenv
import os
from pypdf import PdfReader
from utils import chunk_text
from pathlib import Path

from azure.identity import DefaultAzureCredential
from azure.ai.projects import AIProjectClient
from azure.core.credentials import AzureKeyCredential

from azure.search.documents import SearchClient
from azure.search.documents.models import VectorizedQuery
from azure.ai.inference import EmbeddingsClient
from azure.search.documents.indexes import SearchIndexClient
from azure.search.documents.indexes.models import (
    SearchIndex,
    SearchField,
    SearchFieldDataType,
    SimpleField,
    SearchableField,
    VectorSearch,
    HnswAlgorithmConfiguration,
    VectorSearchProfile,
    SemanticConfiguration,
    SemanticPrioritizedFields,
    SemanticField,
    SemanticSearch,
)

from typing import TypedDict, List, Optional
from langgraph.graph import StateGraph, START, END

#Load the environment variables
load_dotenv()

llm_endpoint = os.getenv("Azure_LLM_ENDPOINT")
embedding_endpoint = os.getenv("AZURE_INFERENCE_ENDPOINT")
search_endpoint = os.getenv("AZURE_SEARCH_ENDPOINT")
admin_key = os.getenv("AZURE_SEARCH_ADMIN_KEY")
credential = DefaultAzureCredential()

deployment_name = "MODEL_DEPLOYMWNT_NAME"

#Initialize the AI Project Client
project_client = AIProjectClient(
    endpoint=llm_endpoint,
    credential=credential,
)

openai_client = project_client.get_openai_client()

#Initialize the Azure AI Inference and Search clients
embedding_client = EmbeddingsClient(
    endpoint=embedding_endpoint,
    credential=AzureKeyCredential(os.getenv("AZURE_INFERENCE_API_KEY"))
)

#Initialize the Azure AI Search client
search_index_client = SearchIndexClient(
    endpoint=search_endpoint,
    credential=AzureKeyCredential(os.getenv("AZURE_SEARCH_ADMIN_KEY"))
)

#Initialize the state
class State(TypedDict):
    query: str
    index_chosen: Optional[str]  # Name of the chosen vector index
    file_path: Optional[str]  # Path to the PDF file to be processed
    index_name: Optional[str]  # Name of the created vector index
    retrieved_chunks: Optional[List[dict]]  # List of retrieved chunks from the vector search
    use_retrieved_chunks: Optional[str]  # Decision on whether to use retrieved chunks or not
    answer: Optional[str]  # Final answer generated by the LLM

#Initialize the state graph
def provide_options(state: State) -> dict:
    choice = state.get("index_chosen", "").strip().lower()

    if choice == "new":
        return {
            "index_chosen": "new",
            "index_name": ""
        }

    if choice == "existing":
        index_name = state.get("index_name", "").strip()

        if not index_name:
            raise ValueError("No existing index was selected.")

        return {
            "index_chosen": "existing",
            "index_name": index_name
        }

    raise ValueError(
        "index_chosen must be either 'new' or 'existing'."
    )

def get_pdf_path(state: State) -> dict:
    return {
        "file_path": state["file_path"]
    }

#Create the vector index
def create_vector_index(state:State) -> dict:
    filename = os.path.splitext(
                os.path.basename(state['file_path'])
            )[0]

    index_name = filename.lower().replace(" ", "-")+"-vector-index"

    fields = [
        SimpleField(
            name="id",
            type=SearchFieldDataType.String,
            key=True
        ),
        SearchableField(
            name="content",
            type=SearchFieldDataType.String,
        ),
        SimpleField(
            name="sourcefile",
            type=SearchFieldDataType.String,
            filterable=True
        ),
        SearchField(
            name ="contentVector",
            type=SearchFieldDataType.Collection(
                SearchFieldDataType.Single
            ),
            searchable=True,
            vector_search_dimensions=3072,
            vector_search_profile_name="my-vector-profile",
        ),
    ]

    vector_search = VectorSearch(
        algorithms=[
            HnswAlgorithmConfiguration(
                name="my-hnsw"
            )
        ],
        profiles=[
            VectorSearchProfile(
                name="my-vector-profile",
                algorithm_configuration_name="my-hnsw",
            )
        ],
    )

    semantic_config = SemanticConfiguration(
        name="default",
        prioritized_fields=SemanticPrioritizedFields(
            content_fields=[SemanticField(field_name="content")],
        )
    )

    semantic_search = SemanticSearch(
        configurations=[semantic_config]
    )


    index = SearchIndex(
        name=index_name,
        fields=fields,
        vector_search=vector_search,
        semantic_search=semantic_search
    )

    result = search_index_client.create_or_update_index(index)

    print(f"Index created successfully: {result.name}")

    return {
        "index_name": index_name
    }

#Ingest the PDF
def ingest_pdf(state:State)-> None:
    pdf_path = Path(state["file_path"])
    chunk_size = 1000
    chunk_overlap = 200

    embedding_batch_size = 16
    embedding_model = os.getenv("AZURE_INFERENCE_MODEL")

    reader = PdfReader(str(pdf_path))
    pages = []

    for page_number, page in enumerate(reader.pages, start=1):
        text = page.extract_text() or ""
        if text.strip():
            pages.append(f"[Page {page_number}]\n{text}")

    full_text = "\n\n".join(pages)

    if not full_text.strip():
        raise ValueError("No text extracted from the PDF.")

    chunks = chunk_text(full_text, chunk_size, chunk_overlap)

    print(f"Chunks prepared: {len(chunks)}")

    search_client = SearchClient(
        endpoint=search_endpoint,
        index_name=state["index_name"],
        credential=AzureKeyCredential(os.getenv("AZURE_SEARCH_ADMIN_KEY"))
    )


    #Initialize the embeddings client
    for start in range(0, len(chunks), embedding_batch_size):
        batch = chunks[start:start + embedding_batch_size]

        documents = []

        response = embedding_client.embed(
            input=batch,
            model=embedding_model,
        )

        embeddings = sorted(
            response.data,
            key=lambda item: item.index,
        )

        for offset, item in enumerate(embeddings):
            chunk_index = start + offset

            documents.append({
                "id": f"{pdf_path.stem.replace(' ', '-')}-chunk-{chunk_index + 1}",
                "content": chunks[chunk_index],
                "sourcefile": str(pdf_path),
                "contentVector": item.embedding
            })

        print(f"Processed chunks {start + 1} to {min(start + embedding_batch_size, len(chunks))}")

        results = search_client.upload_documents(documents)

        succeeded = sum(1 for doc in results if doc.succeeded)

        print(f"Uploaded {succeeded} documents to the index")
        failed = sum(1 for doc in results if not doc.succeeded)

        if failed:
            for result in results:
                if not result.is_ok():
                    print(f"Failed to upload document: {result.error_message}")

#Retrieve the chunks
def retrieve_chunks(state: State) -> dict:
    query = state["query"].strip()

    if not query:
        raise ValueError("Please enter a question.")

    query_vector_response = embedding_client.embed(
        input=[query],
        model=os.getenv("AZURE_INFERENCE_MODEL"),
    )

    query_vector = query_vector_response.data[0].embedding

    search_client = SearchClient(
        endpoint=search_endpoint,
        index_name=state["index_name"],
        credential=AzureKeyCredential(
            os.getenv("AZURE_SEARCH_ADMIN_KEY")
        )
    )

    vector_query = VectorizedQuery(
        vector=query_vector,
        k_nearest_neighbors=20,
        fields="contentVector",
    )

    search_results = search_client.search(
        search_text=query,
        vector_queries=[vector_query],
        select=["content", "sourcefile"],
        top=5,
        query_type="semantic",
        semantic_configuration_name="default"
    )

    retrieved_chunks = []

    for result in search_results:
        print(
            "Source:", result["sourcefile"],
            "\nScore:", result.get("@search.score"),
            "\nReranker:", result.get("@search.rerankerScore"),
            "\nContent:", result["content"][:500],
            "\n" + "-" * 80
        )

        retrieved_chunks.append(
            f"Source: {result['sourcefile']}\n"
            f"Content: {result['content'][:1500]}"
        )

    if not retrieved_chunks:
        return {
            "retrieved_chunks": "No matching chunks found."
        }

    retrieved_text = "\n\n".join(retrieved_chunks)

    return {
        "retrieved_chunks": retrieved_text
    }

#Use the retrieved chunks
def use_retrieved_chunks_tool_or_not(state: State) -> None:

    prompt = f"""
    Decide whether the retrieved document chunks are required to answer
    the user's question.

    Respond with ONLY one word:
    yes
    or
    no

    User Question:
    {state['query']}
    """

    response = openai_client.responses.create(
        model=deployment_name,
        input=prompt
    )

    use_retrieved_chunks = response.output_text.strip().lower()

    return {
        "use_retrieved_chunks": use_retrieved_chunks
    }

#Generate the answer
def generate_answer(state: State) -> dict:

    retrieved_chunks = state.get("retrieved_chunks")

    if retrieved_chunks:
        prompt = f"""
        You are an AI assistant. Use the following context to answer the question.

        Context:
        {retrieved_chunks}

        Question:
        {state['query']}

        Answer:
        """
    else:
        prompt = f"""
        You are an AI assistant. Answer the user's question directly.

        Question:
        {state['query']}

        Answer:
        """

    response = openai_client.responses.create(
        model=deployment_name,
        input=prompt
    )

    return {
        "answer": response.output_text
    }

#Initialize the state graph
builder = StateGraph(State)

#Add nodes
builder.add_node("provide_options", provide_options)
builder.add_node("get_pdf_path", get_pdf_path)
builder.add_node("create_vector_index", create_vector_index)
builder.add_node("ingest_pdf", ingest_pdf)
builder.add_node("retrieve_chunks", retrieve_chunks)
builder.add_node("use_retrieved_chunks_tool_or_not", use_retrieved_chunks_tool_or_not)
builder.add_node("generate_answer", generate_answer)

#Add edges
builder.add_edge(START, "provide_options")


builder.add_conditional_edges(
    "provide_options",
    lambda state: state.get("index_chosen", "").strip().lower(),
    {
        "new": "get_pdf_path",
        "existing": "use_retrieved_chunks_tool_or_not",
    }
)


builder.add_edge("get_pdf_path", "create_vector_index")
builder.add_edge("create_vector_index", "ingest_pdf")
builder.add_edge("ingest_pdf", "use_retrieved_chunks_tool_or_not")


builder.add_conditional_edges(
    "use_retrieved_chunks_tool_or_not",
    lambda state: state.get("use_retrieved_chunks", "").strip().lower(),
    {
        "yes": "retrieve_chunks",
        "no": "generate_answer",
    }
)


builder.add_edge("retrieve_chunks", "generate_answer")

#Compile
graph = builder.compile()


if __name__ == "__main__":
    query = input("Ask a question about the PDF content: ").strip()

    state = {
        "query": query,
    }

    final_state = graph.invoke(state)

    print("\n--- Final Answer ---")
    print(final_state.get("answer", "No answer generated."))